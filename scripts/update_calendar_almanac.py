"""Regenerate local almanac from NAOJ's published JST ephemerides (network only at development time)."""
from html.parser import HTMLParser
from urllib.request import urlopen
from datetime import datetime, timedelta
from pathlib import Path
import json

class Rows(HTMLParser):
    def __init__(self): super().__init__(); self.rows=[]; self.row=None; self.cell=None
    def handle_starttag(self,tag,attrs):
        if tag=='tr': self.row=[]
        if tag in ('td','th'): self.cell=''
    def handle_data(self,data):
        if self.cell is not None: self.cell+=data
    def handle_endtag(self,tag):
        if tag in ('td','th') and self.cell is not None:
            if self.row is not None: self.row.append(self.cell.strip())
            self.cell=None
        if tag=='tr' and self.row is not None: self.rows.append(self.row); self.row=None

import re
phases=[]; terms=[]; urls=[]
for year in range(2023,2028):
    for part in (2,3):
        url=f'https://eco.mtk.nao.ac.jp/koyomi/yoko/{year}/rekiyou{year%100:02}{part}.html'
        urls.append(url)
        parser=Rows(); parser.feed(urlopen(url).read().decode('shift_jis'))
        for row in parser.rows:
            if not row: continue
            dates=[re.fullmatch(r'(\d+)月(\d+)日',x) for x in row]
            match=next((x for x in dates if x),None)
            if not match: continue
            month,day=map(int,match.groups())
            tm=next((re.fullmatch(r'(\d+)時(\d+)分',x) for x in row if re.fullmatch(r'(\d+)時(\d+)分',x)),None)
            dt=datetime(year,month,day,*(map(int,tm.groups()) if tm else [0,0]))
            if part==3 and row[0] in ['朔','望','上弦','下弦']:
                phases.append((dt,row[0]))
            if part==2 :
                degree=next((re.fullmatch(r'(\d+)度',x) for x in row if re.fullmatch(r'(\d+)度',x)),None)
                if degree and int(degree[1])%15==0: terms.append((dt,row[0],int(degree[1])))
        if part==2: assert len([x for x in terms if x[0].year==year]) == 24
        if part==3: assert 48<=len([x for x in phases if x[0].year==year])<=51
phases.sort(); terms.sort()
moons=[x[0] for x in phases if x[1]=='朔']
# A lunar month starts on the JST civil date containing the new moon.
starts=[x.replace(hour=0,minute=0) for x in moons]
months={}
anchors=[]
for solstice,name,degree in terms:
    if name=='冬至': anchors.append(max(i for i,x in enumerate(starts) if x.date()<=solstice.date()))
for a,b in zip(anchors,anchors[1:]):
    leap=None
    if b-a==13:
        leap=next(i for i in range(a+1,b) if not any(starts[i].date()<=t.date()<starts[i+1].date() and d%30==0 for t,_,d in terms))
    m=11
    for i in range(a,b):
        if i>a and i!=leap: m=m%12+1
        months[starts[i]]=m
# Last solstice month and the following month are unambiguous.
for i in range(anchors[-1],len(starts)): months[starts[i]]=(11+i-anchors[-1]-1)%12+1

def swift(s): return json.dumps(s,ensure_ascii=False)
out=['// Generated by scripts/update_calendar_almanac.py. Source: NAOJ 暦要項 2023–2027.', 'import Foundation', 'enum AlmanacData {', '    static let phases: [(String, String)] = [']
for dt,name in phases: out.append(f'        ({swift(dt.isoformat(timespec="minutes"))}, {swift(name)}),')
out+=['    ]','    static let terms: [String: String] = [']
for dt,name,_ in terms: out.append(f'        {swift(dt.strftime("%Y-%m-%d"))}: {swift(name)},')
out+=['    ]','    static let lunarMonths: [(String, Int)] = [']
for dt,m in sorted(months.items()): out.append(f'        ({swift(dt.strftime("%Y-%m-%d"))}, {m}),')
out+=['    ]','}']
Path('Sources/MonitorKit/Tools/AlmanacData.swift').write_text('\n'.join(out)+'\n')
print(f'Generated {len(phases)} phases, {len(terms)} terms, {len(months)} lunar month starts')
